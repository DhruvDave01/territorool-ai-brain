#!/usr/bin/env node
/**
 * Builds the data-model map from the live code (read-only). The repo has almost no migrations (8 framework
 * ones plus the MCP modules'), so the model classes and the query builder calls are the best available
 * description of the schema. A table seen only through `DB::table()` has no model, and its columns are UNKNOWN.
 *
 *   node tools/data-model.js           # writes brain/audits/data/data-model.json + the generated tables in brain/context/data-model.md
 *   node tools/data-model.js --check   # exit 1 if the note is stale
 *
 * Sources: repos/web/app/**\/*.php (Eloquent / Moloquent classes, DB::table / DB::connection calls, module
 * migrations), repos/mobile/App/storage/*.js (Realm schemas). Nothing is written to either repo.
 */
const fs = require('fs');
const path = require('path');
const { ROOT } = require('./lib/vault.js');

const WEB = path.join(ROOT, 'repos/web');
const MOB = path.join(ROOT, 'repos/mobile');
const NOTE = path.join(ROOT, 'brain/context/data-model.md');
const JSON_OUT = path.join(ROOT, 'brain/audits/data/data-model.json');
const START = '<!-- data-model:start (generated by tools/data-model.js; do not edit inside) -->';
const END = '<!-- data-model:end -->';
const read = (p) => fs.readFileSync(p, 'utf8');
const rel = (p) => path.relative(WEB, p);

function walk(dir, re, out = []) {
  if (!fs.existsSync(dir)) return out;
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) { if (!/^(node_modules|vendor|\.)/.test(e.name)) walk(p, re, out); } else if (re.test(e.name)) out.push(p);
  }
  return out;
}
const snakePlural = (cls) => {
  const s = cls.replace(/([a-z0-9])([A-Z])/g, '$1_$2').toLowerCase();
  return /(s|x|ch|sh)$/.test(s) ? `${s}es` : /[^aeiou]y$/.test(s) ? `${s.slice(0, -1)}ies` : `${s}s`;
};
const lineOf = (text, idx) => text.slice(0, idx).split('\n').length;

const phpFiles = walk(path.join(WEB, 'app'), /\.php$/);
const models = [];
// Comments are blanked (keeping line breaks) so commented-out declarations are never read as real.
const code = (t) => t.replace(/\/\*[\s\S]*?\*\//g, (c) => c.replace(/[^\n]/g, ' ')).replace(/^\s*(\/\/|#).*$/gm, '');
for (const f of phpFiles) {
  const t = code(read(f));
  const m = t.match(/class\s+(\w+)\s+extends\s+(Model|Eloquent|Moloquent|Authenticatable|\\?Jenssegers\\Mongodb\\Eloquent\\Model|Pivot)\b/);
  if (!m) continue;
  const table = (t.match(/\$(table|collection)\s*=\s*['"]([^'"]+)['"]/) || [])[2];
  const connection = (t.match(/\$connection\s*=\s*['"]([^'"]+)['"]/) || [])[1] || (/Moloquent|Mongodb/.test(m[2]) ? 'mongodb' : 'mysql (default)');
  const fillable = ((t.match(/\$fillable\s*=\s*\[([\s\S]*?)\]/) || [])[1] || '').match(/['"][^'"]+['"]/g);
  const rels = [...t.matchAll(/function\s+(\w+)\s*\([^)]*\)\s*\{[^}]*?\$this->(hasMany|hasOne|belongsTo|belongsToMany|hasManyThrough|morphMany|morphTo)\(\s*['"]?\\?([\w\\]+)(?:::class)?/g)]
    .map((r) => `${r[1]} → ${r[2]}(${r[3].split('\\').pop()})`);
  models.push({
    class: m[1], file: rel(f), line: lineOf(t, m.index), table: table || snakePlural(m[1]), tableDeclared: !!table, connection,
    fillable: fillable ? fillable.map((s) => s.slice(1, -1)) : [], relations: rels,
  });
}

// Query-builder tables (no model needed) and how often each is used.
const dbTables = {};
for (const f of phpFiles) {
  const t = code(read(f));
  for (const m of t.matchAll(/DB::(?:connection\(\s*['"](\w+)['"]\s*\)->)?(?:table|collection)\(\s*['"]([\w.]+)['"]/g)) {
    const k = m[2];
    const d = (dbTables[k] = dbTables[k] || { uses: 0, files: new Set(), connection: m[1] || 'default' });
    d.uses++; d.files.add(rel(f));
  }
}
// Module migrations (the only schema definitions in the repo besides the 8 framework ones).
const migrations = [...walk(path.join(WEB, 'database/migrations'), /\.php$/), ...walk(path.join(WEB, 'app'), /\.php$/).filter((f) => /\/database\/migrations\//.test(f))]
  .map((f) => { const t = read(f); return { file: rel(f), creates: [...t.matchAll(/Schema::(?:connection\([^)]*\)->)?create\(\s*['"](\w+)['"]/g)].map((m) => m[1]) }; })
  .filter((m) => m.creates.length);

// Mobile Realm schemas.
const realm = [];
for (const f of walk(path.join(MOB, 'App/storage'), /\.js$/)) {
  const t = read(f);
  // properties: { name: { type: … }, … } — take the keys at nesting depth 1 only.
  for (const m of t.matchAll(/name:\s*['"](\w+)['"]\s*,\s*(?:primaryKey:\s*['"](\w+)['"]\s*,\s*)?properties:\s*\{/g)) {
    let i = m.index + m[0].length, depth = 1, body = '';
    while (i < t.length && depth) { const ch = t[i++]; if (ch === '{') depth++; else if (ch === '}') depth--; if (depth === 1 && ch !== '}') body += ch; else if (depth > 1) body += ' '; }
    const props = [...body.replace(/\/\*[\s\S]*?\*\//g, '').matchAll(/(\w+)\s*:/g)].map((p) => p[1]);
    realm.push({ schema: m[1], file: path.relative(MOB, f), line: lineOf(t, m.index), primaryKey: m[2] || null, properties: props });
  }
}

const modelTables = new Set(models.map((m) => m.table));
const orphanTables = Object.entries(dbTables).filter(([k]) => !modelTables.has(k)).sort((a, b) => b[1].uses - a[1].uses);
const data = {
  models: models.sort((a, b) => a.class.localeCompare(b.class)),
  queryBuilderTables: Object.fromEntries(Object.entries(dbTables).map(([k, v]) => [k, { uses: v.uses, connection: v.connection, files: [...v.files].sort() }])),
  migrations, realm,
};

const esc = (s) => String(s).replace(/\|/g, '\\|');
const out = [
  `**${models.length} model classes** (${models.filter((m) => m.connection === 'mongodb').length} on MongoDB) · **${Object.keys(dbTables).length} tables reached through \`DB::table()\`**, of which ${orphanTables.length} have no model · ${migrations.length} migration files define ${migrations.reduce((n, m) => n + m.creates.length, 0)} tables · ${realm.length} Realm schemas on mobile`,
  '',
  '### Models',
  '',
  '| Model | Table | Store | Declared? | Fillable (first 8) | Relations | File |',
  '|---|---|---|---|---|---|---|',
  ...data.models.map((m) => `| \`${m.class}\` | \`${m.table}\` | ${m.connection} | ${m.tableDeclared ? 'yes' : 'inferred'} | ${esc(m.fillable.slice(0, 8).join(', ')) || '—'}${m.fillable.length > 8 ? ` +${m.fillable.length - 8}` : ''} | ${esc(m.relations.join('; ')) || '—'} | \`${m.file}:${m.line}\` |`),
  '',
  '### Tables used without a model (query builder only; columns UNKNOWN unless read in the calling code)',
  '',
  '| Table | Uses | Connection | Files (first 3) |',
  '|---|---|---|---|',
  ...orphanTables.map(([k, v]) => `| \`${k}\` | ${v.uses} | ${v.connection} | ${[...v.files].slice(0, 3).map((f) => `\`${f}\``).join(', ')}${v.files.size > 3 ? ` +${v.files.size - 3}` : ''} |`),
  '',
  '### Schema definitions in the repo (migrations)',
  '',
  '| File | Creates |',
  '|---|---|',
  ...migrations.map((m) => `| \`${m.file}\` | ${m.creates.map((c) => `\`${c}\``).join(', ')} |`),
  '',
  '### Mobile local storage (Realm)',
  '',
  '| Schema | Primary key | Properties | File |',
  '|---|---|---|---|',
  ...realm.map((r) => `| \`${r.schema}\` | ${r.primaryKey || '—'} | ${esc(r.properties.join(', '))} | \`${r.file}:${r.line}\` |`),
].join('\n');

const note = read(NOTE);
const s = note.indexOf(START), e = note.indexOf(END);
if (s < 0 || e < 0) { console.error('data-model.md is missing its generated markers.'); process.exit(2); }
const next = `${note.slice(0, s + START.length)}\n${out}\n${note.slice(e)}`;
if (process.argv.includes('--check')) {
  if (next !== note) { console.error('data-model.md is STALE: run node tools/data-model.js'); process.exit(1); }
  console.log('data-model.md is current'); process.exit(0);
}
fs.writeFileSync(JSON_OUT, `${JSON.stringify(data, null, 1)}\n`);
fs.writeFileSync(NOTE, next);
console.log(`data-model: ${models.length} models, ${Object.keys(dbTables).length} query-builder tables, ${realm.length} Realm schemas`);
