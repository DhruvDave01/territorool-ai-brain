#!/usr/bin/env node
/**
 * Renders the runtime web page inventory (per role) and the access matrix into brain/context/web-flows.md
 * from brain/audits/data/web-explore*.json (written by tools/web-explore.js). Structure only: no values.
 *
 *   node tools/web-inventory.js           # rewrite the generated section
 *   node tools/web-inventory.js --check   # exit 1 if stale
 */
const fs = require('fs');
const path = require('path');
const { ROOT } = require('./lib/vault.js');

const DATA = path.join(ROOT, 'brain/audits/data');
const NOTE = path.join(ROOT, 'brain/context/web-flows.md');
const START = '<!-- web-inventory:start (generated by tools/web-inventory.js; do not edit inside) -->';
const END = '<!-- web-inventory:end -->';

const main = JSON.parse(fs.readFileSync(path.join(DATA, 'web-explore.json'), 'utf8'));
const extras = fs.readdirSync(DATA).filter((f) => /^web-explore\..+\.json$/.test(f)).sort()
  .map((f) => ({ file: f, data: JSON.parse(fs.readFileSync(path.join(DATA, f), 'utf8')) }));
const esc = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim();
const skipBtn = /^(Upgrade|×|Close|Send|Toggle navigation)$/;
// Every Blade page carries the same CRM-connect modals (sfdc, HubSpot, Karma); they are listed once, not per page.
const SHELL_FORMS = new Set(['/sfdc', '/save-hubspot-api-key', '/save-karmacrm-api-key', '/javascript:void(0)', '#', '']);

const lines = [`Captured **${main.capturedAt.slice(0, 16).replace('T', ' ')} UTC** on staging by \`tools/web-explore.js\` (read-only guard). Screenshots: \`workspace/qa-evidence/${main.capturedAt.slice(0, 10)}/web/<role>/\`.`, ''];

lines.push('### Login outcome per role', '', '| Role | Login page | Captcha | Result | Landed on |', '|---|---|---|---|---|');
const rows = Object.entries(main.roles).map(([r, v]) => [r, v]);
for (const x of extras) for (const [r, v] of Object.entries(x.data.roles)) rows.push([`${r} (run \`${x.file}\`)`, v]);
for (const [r, v] of rows) lines.push(`| ${r} | \`${v.loginPage || ''}\` | ${v.captchaOnLogin ? '**yes**' : 'no'} | ${v.loginOk ? 'OK' : `**BLOCKED**${v.loginError ? `: ${esc(v.loginError).slice(0, 90)}` : ''}`} | \`${v.landed || ''}\` |`);

lines.push('', '### Access matrix (each role requested each path; where it landed)', '');
const roles = Object.keys(main.probe);
const paths = Object.keys(main.probe[roles[0]] || {});
lines.push(`| Path | ${roles.join(' | ')} |`, `|---|${roles.map(() => '---').join('|')}|`);
for (const p of paths) lines.push(`| \`${p}\` | ${roles.map((r) => { const x = main.probe[r][p]; if (!x || x.error) return 'error'; return x.final === p ? `✅ ${x.status}` : `↪ \`${x.final}\``; }).join(' | ')} |`);

for (const [role, v] of Object.entries(main.roles)) {
  if (!(v.pages || []).length) continue;
  const nav = (v.pages[0].nav || []).filter((n) => !/^Toggle navigation/.test(n));
  lines.push('', `### ${role}: pages reached (${v.pages.length})`, '', nav.length ? `**Menu:** ${nav.map(esc).join(' · ')}` : '**Menu:** React sidebar (not matched by the menu selector; see `web-surfaces.md` §1)', '');
  lines.push('| # | Requested → final | HTTP | Heading | Main actions | Page forms (fields) | Tables (columns) |', '|---|---|---|---|---|---|---|');
  v.pages.forEach((p, i) => {
    const forms = (p.forms || []).filter((f) => !SHELL_FORMS.has(f.action)).map((f) => `${f.method} \`${esc(f.action) || '(self)'}\` (${f.fields.length})`).join('; ');
    const acts = (p.buttons || []).filter((b) => !skipBtn.test(b)).slice(0, 6).map(esc).join(' / ');
    const tables = (p.tables || []).filter((t) => t.length).map((t) => t.length).join(', ');
    lines.push(`| ${i + 1} | \`${esc(p.requested)}\`${p.final !== p.requested ? ` → \`${esc(p.final)}\`` : ''} | ${p.status ?? '—'} | ${esc(p.h1) || '—'} | ${acts || '—'} | ${forms || '—'} | ${tables || '—'} |`);
  });
}
const out = lines.join('\n');
const note = fs.readFileSync(NOTE, 'utf8');
const s = note.indexOf(START), e = note.indexOf(END);
if (s < 0 || e < 0) { console.error('web-flows.md is missing its generated markers.'); process.exit(2); }
const next = `${note.slice(0, s + START.length)}\n${out}\n${note.slice(e)}`;
if (process.argv.includes('--check')) { if (next !== note) { console.error('web-flows.md is STALE: run node tools/web-inventory.js'); process.exit(1); } console.log('web-flows.md is current'); process.exit(0); }
fs.writeFileSync(NOTE, next);
console.log(`web-inventory: ${Object.values(main.roles).reduce((n, r) => n + (r.pages || []).length, 0)} pages, ${paths.length} probed paths`);
