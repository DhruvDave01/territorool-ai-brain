#!/usr/bin/env node
/**
 * Renders the one cross-tool brief into each AI coding tool's instruction file.
 *
 * Source:  brain/context/agent-brief.md   (a normal brain note — edit THAT)
 * Targets: AGENTS.md                            Codex, and most other tools
 *          .cursor/rules/territool-brain.mdc    Cursor (needs its own frontmatter)
 *          .github/copilot-instructions.md      GitHub Copilot / VS Code
 *
 * Why generated: four hand-maintained copies of the same rules drift within a week, and a stale
 * non-negotiable is worse than none. One source, many renderings — the same pattern the graph and the
 * Obsidian vault already use.
 *
 * CLAUDE.md is NOT generated: it is hand-written, richer, and Claude-specific. It links here instead.
 *
 * Usage (from territool-brain/): node tools/sync-agent-files.js [--check]
 */
const fs = require('fs');
const path = require('path');
const { ROOT } = require('./lib/vault.js');

const CHECK = process.argv.includes('--check');
const SOURCE = 'brain/context/agent-brief.md';

/** Strip the note's YAML frontmatter and the generated "Linked" block — neither belongs in a tool file. */
function body(md) {
  let t = md;
  if (t.startsWith('---\n')) {
    const end = t.indexOf('\n---\n', 3);
    if (end !== -1) t = t.slice(end + 5);
  }
  const lines = t.split('\n');
  let start = -1;
  let stop = -1;
  for (let i = lines.length - 1; i >= 0; i--) {
    if (stop === -1) { if (lines[i].trim() === '%% brain-links:end %%') stop = i; continue; }
    if (lines[i].trim() === '%% brain-links:start %%') { start = i; break; }
  }
  if (start !== -1 && stop !== -1) t = lines.slice(0, start).join('\n');
  return t.replace(/^\n+/, '').replace(/\s*$/, '\n');
}

const src = fs.readFileSync(path.join(ROOT, SOURCE), 'utf8');
const brief = body(src);
const banner = `<!-- GENERATED from ${SOURCE} by tools/sync-agent-files.js — do not edit this file. -->`;

const TARGETS = {
  // Codex and the general fallback.
  'AGENTS.md': `${banner}\n\n${brief}`,

  // Cursor project rules need frontmatter; alwaysApply keeps the non-negotiables in every request.
  '.cursor/rules/territool-brain.mdc':
    `---\ndescription: Territool brain — non-negotiables, verified commands and where the knowledge lives\nglobs:\nalwaysApply: true\n---\n\n${banner}\n\n${brief}`,

  '.github/copilot-instructions.md': `${banner}\n\n${brief}`,
};

let changed = 0;
const stale = [];
for (const [rel, text] of Object.entries(TARGETS)) {
  const abs = path.join(ROOT, rel);
  const prev = fs.existsSync(abs) ? fs.readFileSync(abs, 'utf8') : null;
  if (prev === text) continue;
  stale.push(rel);
  changed++;
  if (CHECK) continue;
  fs.mkdirSync(path.dirname(abs), { recursive: true });
  fs.writeFileSync(abs, text);
}

if (CHECK) {
  if (stale.length) {
    console.error(`sync-agent-files: ${stale.length} out of date: ${stale.join(', ')}`);
    process.exit(1);
  }
  console.log('sync-agent-files: all tool files match the brief.');
  process.exit(0);
}
console.log(`sync-agent-files: ${Object.keys(TARGETS).length} tool files rendered from ${SOURCE} (${changed} updated)`);
for (const rel of Object.keys(TARGETS)) console.log(`  ${rel}`);
