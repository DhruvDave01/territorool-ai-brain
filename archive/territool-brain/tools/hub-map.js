#!/usr/bin/env node
/**
 * The brain as a hub-and-spoke map (2026-09-17). A second, simpler picture of the same index.
 *
 * Writes:
 *  - views/hub-map/            a small Obsidian vault: Home → area hubs → feature/journey hubs → leaves,
 *                              ONE link per note, so the graph draws clean stars. Each leaf links back to
 *                              its full note in the main vault with an obsidian:// URL (not a graph edge).
 *  - workspace/brain-graph/hub-data.js   the same tree for the shared D3 page's "Hub map" button.
 *
 * Left out on purpose (still in the full vault): code files, brain scripts, commit records.
 * Everything here is generated: never hand-edit views/hub-map/ (the main vault ignores that folder).
 *
 * Usage: node tools/hub-map.js [--check] [--quiet]     (--check: exit 1 if the output is stale)
 */
const fs = require('fs');
const path = require('path');
const { buildHubs, areaOf } = require('./lib/hubs.js');
const { noteFor, safe } = require('./lib/nodes.js');

const ROOT = path.resolve(__dirname, '..');
const OUT = path.join(ROOT, 'views', 'hub-map');
const D3_OUT = path.join(ROOT, 'workspace', 'brain-graph', 'hub-data.js');
const MAIN_VAULT = path.basename(ROOT);
const MARK = '<!-- generated by tools/hub-map.js; this whole file is rewritten. -->';
const CHECK = process.argv.includes('--check');
const QUIET = process.argv.includes('--quiet');

const index = JSON.parse(fs.readFileSync(path.join(ROOT, 'brain/audits/data/brain-index.json'), 'utf8'));
const { NODE, shown, parent, areas, excludedCounts } = buildHubs(index);

// Colours match workspace/brain-graph/index.html so the two pictures read the same.
const COLOR = {
  doc: '#d4d6db', flow: '#6fdc9a', mflow: '#ff8fb8', capture: '#9fb4c8', video: '#ff9f1c', rule: '#6ea8fe',
  gate: '#b39cff', decision: '#f3c46a', gap: '#ef6a5a', screen: '#4cc9d6', code: '#80848c',
};
const KIND = {
  doc: 'Document', flow: 'Product feature', mflow: 'App journey', capture: 'Screenshot', video: 'Screen recording',
  rule: 'Coding rule', gate: 'Quality check', decision: 'Owner decision', gap: 'Problem found', screen: 'App screen',
};

// ------------------------------------------------------------------ file names
const used = new Set();
const fileName = (folder, label, ref) => {
  const base = safe(label).replace(/[#^[\]/]/g, '-').replace(/^[.\s]+/, '').slice(0, 90) || 'Untitled';
  let p = `${folder}/${base}.md`;
  if (used.has(p.toLowerCase())) p = `${folder}/${base} (${safe(ref || '').replace(/[#^[\]/]/g, '-').slice(0, 40)}).md`;
  for (let i = 2; used.has(p.toLowerCase()); i++) p = `${folder}/${base} ${i}.md`;
  used.add(p.toLowerCase());
  return p;
};
const link = (p, label) => `[[${p.replace(/\.md$/, '')}|${String(label).replace(/[[\]|]/g, '')}]]`;
const clean = (s, n) => {
  const t = String(s || '').replace(/\[\[|\]\]/g, '').replace(/\s+/g, ' ').trim();
  return t.length > n ? `${t.slice(0, n - 1).trimEnd()}…` : t;
};

const HOME = 'Territool brain.md';
used.add(HOME.toLowerCase());
const AREA_FILE = new Map(areas.map(([key, label]) => [key, fileName('Hubs', label, key)]));
const AREA_LABEL = new Map(areas.map(([key, label]) => [key, label]));
const folderOf = (n) => (n.g === 'flow' ? 'Features' : n.g === 'mflow' ? 'Journeys' : AREA_LABEL.get(areaOf(n)) || 'Documents');
const NOTE = new Map();
const ordered = [...shown].sort((a, b) => {
  const pa = NODE.get(a).g === 'flow' || NODE.get(a).g === 'mflow' ? 0 : 1;
  const pb = NODE.get(b).g === 'flow' || NODE.get(b).g === 'mflow' ? 0 : 1;
  return pa - pb || (a < b ? -1 : 1);
});
for (const id of ordered) {
  const n = NODE.get(id);
  NOTE.set(id, fileName(folderOf(n), n.l || n.ref || id, n.ref || id));
}

// ------------------------------------------------------------------ render
const files = new Map();
const front = (tags) => `---\ntags: [${tags.join(', ')}]\n---\n`;

const areaSize = new Map();
for (const p of parent.values()) if (p.hub) areaSize.set(p.hub, (areaSize.get(p.hub) || 0) + 1);
const nodeSize = new Map();
for (const p of parent.values()) if (p.node) nodeSize.set(p.node, (nodeSize.get(p.node) || 0) + 1);

const left = Object.entries(excludedCounts).map(([k, v]) => `${v} ${k}${v === 1 ? '' : 's'}`).join(', ');
files.set(HOME, [
  front(['hub/home']), MARK, '', '# Territool brain — hub map', '',
  'The brain drawn as hubs and spokes: every note has exactly one parent. Open the **graph view** to see it.',
  `The full, cross-linked brain is the \`${MAIN_VAULT}\` vault; each note here links to its full version.`, '',
  `Shown: ${shown.size} notes. Left out: ${left || 'nothing'}.`, '',
  '## Hubs', '',
  ...areas.filter(([k]) => areaSize.get(k)).map(([k, label]) => `- ${link(AREA_FILE.get(k), label)} · ${areaSize.get(k)}`), '',
].join('\n'));

for (const [key, label, desc] of areas) {
  if (!areaSize.get(key)) continue;
  files.set(AREA_FILE.get(key), [
    front(['hub/area']), MARK, '', `# ${label}`, '', desc, '', `${areaSize.get(key)} notes hang from this hub.`, '',
    `Back to ${link(HOME, 'Territool brain')}.`, '',
  ].join('\n'));
}

const openUrl = (n) => {
  const p = noteFor(n);
  return p ? `obsidian://open?vault=${encodeURIComponent(MAIN_VAULT)}&file=${encodeURIComponent(p.replace(/\.md$/, ''))}` : null;
};
for (const id of ordered) {
  const n = NODE.get(id);
  const par = parent.get(id);
  const up = par.hub ? link(AREA_FILE.get(par.hub), AREA_LABEL.get(par.hub)) : link(NOTE.get(par.node), NODE.get(par.node).l);
  const hub = n.g === 'flow' || (n.g === 'mflow' && n.kind === 'journey');
  const kind = n.kind === 'part' ? 'Shared journey part' : KIND[n.g] || n.g;
  const url = openUrl(n);
  files.set(NOTE.get(id), [
    front([hub ? 'hub/node' : `leaf/${n.g}`]), MARK, '', `# ${clean(n.l || n.ref, 120)}`, '',
    `${kind}${n.ref && n.ref !== n.l ? ` · \`${clean(n.ref, 80)}\`` : ''}${hub && nodeSize.get(id) ? ` · ${nodeSize.get(id)} notes hang from this hub` : ''}`, '',
    ...(n.d ? [clean(n.d, 400), ''] : []),
    `Part of ${up}.`, '',
    ...(url ? [`[Open the full note](${url})`, ''] : []),
  ].join('\n'));
}

// Vault config: written once; the colour groups are put back if Obsidian empties them.
const rgb = (hex) => ({ a: 1, rgb: parseInt(hex.slice(1), 16) });
const GRAPH = {
  'collapse-filter': true, search: '', showTags: false, showAttachments: false, hideUnresolved: true, showOrphans: false,
  'collapse-color-groups': true,
  colorGroups: [
    { query: 'tag:#hub/home', color: rgb('#ffffff') },
    { query: 'tag:#hub/area', color: rgb('#8a8f99') },
    ...Object.entries(COLOR).map(([g, c]) => ({ query: g === 'flow' || g === 'mflow' ? `tag:#hub/node path:${g === 'flow' ? 'Features' : 'Journeys'}` : `tag:#leaf/${g}`, color: rgb(c) })),
    { query: 'tag:#leaf/flow OR tag:#leaf/mflow', color: rgb('#ff8fb8') },
  ],
  'collapse-display': true, showArrow: false, textFadeMultiplier: -1, nodeSizeMultiplier: 1.3, lineSizeMultiplier: 0.7,
  'collapse-forces': true, centerStrength: 0.45, repelStrength: 12, linkStrength: 1, linkDistance: 40, scale: 0.3, close: false,
};
const CONFIG = {
  'app.json': { alwaysUpdateLinks: false, newLinkFormat: 'absolutePath', showUnsupportedFiles: false, defaultViewMode: 'preview', readableLineLength: true },
  'appearance.json': { accentColor: '#6ea8fe', theme: 'obsidian' },
  'core-plugins.json': { 'file-explorer': true, 'global-search': true, switcher: true, graph: true, backlink: true, 'page-preview': true, bookmarks: true, 'command-palette': true },
  'bookmarks.json': { items: [{ type: 'file', path: HOME, title: 'Home' }, { type: 'graph', title: 'Hub map' }] },
  'graph.json': GRAPH,
};

// D3 page: parent of each shown node as an index into DATA.nodes, or a hub key.
const POS = new Map(index.nodes.map((n, i) => [n.id, i]));
const d3data = {
  // The page ignores this file unless it was built from the same index as graph-data.js.
  gen: index.generatedAt,
  n: index.nodes.length,
  hubs: areas.filter(([k]) => areaSize.get(k)).map(([k, label, desc]) => ({ k, l: label, d: desc })),
  parent: Object.fromEntries(ordered.map((id) => {
    const p = parent.get(id);
    return [POS.get(id), p.hub ? `h:${p.hub}` : POS.get(p.node)];
  })),
};
const d3text = `// generated by tools/hub-map.js from brain-index.json — do not edit\nwindow.BRAIN_HUBS = ${JSON.stringify(d3data)};\n`;

// ------------------------------------------------------------------ write / check
const stale = [];
const want = (abs, text) => {
  const cur = fs.existsSync(abs) ? fs.readFileSync(abs, 'utf8') : null;
  if (cur === text) return;
  stale.push(path.relative(ROOT, abs));
  if (!CHECK) { fs.mkdirSync(path.dirname(abs), { recursive: true }); fs.writeFileSync(abs, text); }
};
for (const [p, text] of files) want(path.join(OUT, p), text);
want(D3_OUT, d3text);

// Remove notes this tool wrote earlier that no longer exist (only files carrying the marker).
const removed = [];
(function walk(dir) {
  if (!fs.existsSync(dir)) return;
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const abs = path.join(dir, e.name);
    if (e.name.startsWith('.')) continue;
    if (e.isDirectory()) { walk(abs); continue; }
    const rel = path.relative(OUT, abs);
    if (!e.name.endsWith('.md') || files.has(rel)) continue;
    if (!fs.readFileSync(abs, 'utf8').includes(MARK)) continue;
    removed.push(rel);
    if (!CHECK) fs.unlinkSync(abs);
  }
}(OUT));

let config = 0;
if (!CHECK) {
  const obs = path.join(OUT, '.obsidian');
  fs.mkdirSync(obs, { recursive: true });
  for (const [name, value] of Object.entries(CONFIG)) {
    const abs = path.join(obs, name);
    if (fs.existsSync(abs)) {
      if (name !== 'graph.json') continue;
      let live; try { live = JSON.parse(fs.readFileSync(abs, 'utf8')); } catch { live = null; }
      if (live && Array.isArray(live.colorGroups) && live.colorGroups.length) continue;
      fs.writeFileSync(abs, `${JSON.stringify({ ...(live || {}), colorGroups: value.colorGroups }, null, 2)}\n`);
      config++;
      continue;
    }
    fs.writeFileSync(abs, `${JSON.stringify(value, null, 2)}\n`);
    config++;
  }
}

if (CHECK) {
  if (stale.length || removed.length) {
    console.error(`hub-map: out of date — ${stale.length} to write, ${removed.length} to remove (run node tools/hub-map.js)`);
    process.exit(1);
  }
  if (!QUIET) console.log(`hub-map: current (${files.size} notes).`);
  process.exit(0);
}
if (!QUIET) {
  console.log(`hub-map: ${files.size} notes (${shown.size} nodes + ${files.size - shown.size} hubs) → views/hub-map/ · left out: ${left}`);
  console.log(`  updated ${stale.length}, removed ${removed.length}${config ? `, config ${config}` : ''}`);
}
