#!/usr/bin/env node
/**
 * Builds the V2 API endpoint map from the live code (read-only).
 *
 *   node tools/api-map.js            # writes brain/audits/data/api-map.json + the generated table in brain/context/api-map.md
 *   node tools/api-map.js --check    # exit 1 if the note is stale against the code
 *
 * Sources (all read, never written):
 *   repos/web/routes/api.php                              every v2 route, its HTTP method and auth group
 *   repos/web/app/Api/V2/Controllers/*.php (+ Http ones)  the line each action starts on
 *   repos/mobile/App/config/index.js + App/**             which endpoints the mobile app calls
 *   repos/web/app/{UserMcp,FindMcp}/**                    which endpoints the customer MCPs dispatch
 *   brain/context/flows.md                                which feature each endpoint belongs to
 *
 * "kind" is INFERRED from the endpoint name and is labelled so; it is a triage hint, not a verified fact.
 */
const fs = require('fs');
const path = require('path');
const { ROOT } = require('./lib/vault.js');

const WEB = path.join(ROOT, 'repos/web');
const MOB = path.join(ROOT, 'repos/mobile');
const NOTE = path.join(ROOT, 'brain/context/api-map.md');
const JSON_OUT = path.join(ROOT, 'brain/audits/data/api-map.json');
const START = '<!-- api-map:start (generated by tools/api-map.js; do not edit inside) -->';
const END = '<!-- api-map:end -->';
const read = (p) => fs.readFileSync(p, 'utf8');

function walk(dir, re, out = []) {
  if (!fs.existsSync(dir)) return out;
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) { if (!/^(node_modules|Archive|\.)/.test(e.name)) walk(p, re, out); } else if (re.test(e.name)) out.push(p);
  }
  return out;
}

// 1. Routes: only the v2 block; commented lines are skipped (V1 is dead, S0.6).
const api = read(path.join(WEB, 'routes/api.php'));
const v2 = api.slice(api.indexOf("$api->version('v2'"));
const routes = [];
let authed = false;
v2.split('\n').forEach((raw, i) => {
  const line = raw.trim();
  if (line.startsWith('//')) return;
  if (/middleware'\s*=>\s*'jwt\.refresh'/.test(line)) authed = true;
  const m = line.match(/\$api->(get|post|put|delete|patch)\(\s*'([^']+)'\s*,\s*'\\?([^'@]+)@([^']+)'/);
  if (!m) return;
  routes.push({ method: m[1].toUpperCase(), uri: m[2], controller: m[3].replace(/^App\\/, '').replace(/\\/g, '/'), action: m[4], auth: authed ? 'JWT (jwt.refresh)' : 'public' });
});
const apiLineOffset = api.slice(0, api.indexOf("$api->version('v2'")).split('\n').length;

// 2. Action line numbers.
const lineCache = {};
for (const r of routes) {
  const file = path.join(WEB, 'app', `${r.controller.replace(/^Http\//, 'Http/')}.php`);
  if (!lineCache[file]) lineCache[file] = fs.existsSync(file) ? read(file).split('\n') : null;
  const lines = lineCache[file];
  const idx = lines ? lines.findIndex((l) => new RegExp(`function\\s+${r.action}\\s*\\(`, 'i').test(l)) : -1;
  r.at = lines ? `app/${r.controller}.php${idx >= 0 ? `:${idx + 1}` : ' (action not found)'}` : `app/${r.controller}.php (file not found)`;
}

// 3. Mobile consumers: URL_* constants and bare string literals across App/.
const cfg = read(path.join(MOB, 'App/config/index.js'));
const constOf = {};
for (const m of cfg.matchAll(/^export const ([A-Z][A-Z0-9_]+)\s*=\s*['"]([^'"]+)['"]/gm)) (constOf[m[2]] = constOf[m[2]] || []).push(m[1]);
const appFiles = walk(path.join(MOB, 'App'), /\.(js|jsx|ts|tsx)$/).filter((f) => !f.endsWith('config/index.js'));
const appText = appFiles.map((f) => [path.relative(MOB, f), read(f)]);
for (const r of routes) {
  const consts = constOf[r.uri] || [];
  const users = new Set();
  for (const [rel, text] of appText) {
    if (consts.some((c) => new RegExp(`\\b${c}\\b`).test(text)) || new RegExp(`['"\`/]${r.uri.replace(/[{}]/g, '')}['"\`?]`).test(text)) users.add(rel);
  }
  r.mobile = { constants: consts, files: [...users].sort(), definedOnly: consts.length > 0 && users.size === 0 };
}

// 4. MCP consumers.
const mcpFiles = [...walk(path.join(WEB, 'app/UserMcp'), /\.php$/), ...walk(path.join(WEB, 'app/FindMcp'), /\.php$/)];
const mcpText = mcpFiles.map((f) => [path.relative(WEB, f), read(f)]);
for (const r of routes) {
  const re = new RegExp(`(call\\(\\s*'(get|post)'\\s*,\\s*'${r.uri}'|'uri'\\s*=>\\s*'${r.uri}')`);
  r.mcp = mcpText.filter(([, t]) => re.test(t)).map(([rel]) => rel.split('/').slice(1, 2)[0]).filter((v, i, a) => a.indexOf(v) === i);
}

// 5. Feature mapping from flows.md (backticked endpoint names in the "entry points" column).
const flows = read(path.join(ROOT, 'brain/context/flows.md'));
for (const r of routes) {
  r.flows = [];
  for (const row of flows.split('\n').filter((l) => /^\| \**F\d{2}/.test(l))) {
    const id = row.match(/F\d{2}/)[0];
    const names = [...row.matchAll(/`([^`]+)`/g)].map((m) => m[1]);
    const hit = names.some((n) => n === r.uri || (n.endsWith('*') && r.uri.startsWith(n.slice(0, -1))) || n.split(/[\s/]/).includes(r.uri));
    if (hit && !r.flows.includes(id)) r.flows.push(id);
  }
}

// 6. Kind (INFERRED from the name).
const kindOf = (r) => {
  const u = r.uri.toLowerCase();
  if (/webhook|revenue-subscription|revenuecate/.test(u)) return 'webhook';
  if (/buycontacts|redeem|saveaileads|cancelsubscription|package-upgrade/.test(u)) return 'paid/billing';
  if (/sync|zapier|shareroute|invite|recovery|reset|addticket|notify|notifications$/.test(u)) return 'external side effect';
  if (/^(get|fetch|check|search|simple|advance|notificationlist|routelist|contactlist|companylist|companydetail|companyname|companycontact|citysearch|unread|getuser|newrelease)/.test(u) || /list$/.test(u) || r.method === 'GET') {
    if (/fetchallcontacts|fetchclaude|fetchopencorporates|getapollo|getcongnism|getbizpedia|getopencorporates|getaileads|gettop50|aileadgoogle|getyelp/.test(u)) return 'read (provider call; may cost)';
    if (/uploaderror\/(append|delete)|routeregenerate|cancelsubscription/.test(u)) return 'write (GET)';
    return 'read';
  }
  if (/remove|delete/.test(u)) return 'delete';
  return 'write';
};
routes.forEach((r) => { r.kind = kindOf(r); });

// Output.
const data = { generatedFrom: { routes: 'repos/web/routes/api.php', v2StartsAtLine: apiLineOffset }, count: routes.length, routes };
const esc = (s) => String(s).replace(/\|/g, '\\|');
const table = [
  `**${routes.length} v2 routes** · ${routes.filter((r) => r.auth === 'public').length} public · ${routes.filter((r) => r.auth !== 'public').length} behind \`jwt.refresh\` · mobile uses ${routes.filter((r) => r.mobile.files.length).length} · customer MCP uses ${routes.filter((r) => r.mcp.length).length} · with no consumer found in mobile or MCP: ${routes.filter((r) => !r.mobile.files.length && !r.mcp.length).length}`,
  '',
  '| # | Method | URI | Auth | Kind *(inferred)* | Action | Features | Mobile files | MCP |',
  '|---|---|---|---|---|---|---|---|---|',
  ...routes.map((r, i) => `| ${i + 1} | ${r.method} | \`${esc(r.uri)}\` | ${r.auth === 'public' ? '**public**' : 'JWT'} | ${r.kind} | \`${esc(r.at)}\` | ${r.flows.join(', ') || '—'} | ${r.mobile.files.length ? `${r.mobile.files.length}${r.mobile.constants.length ? ` (\`${r.mobile.constants[0]}\`)` : ''}` : r.mobile.definedOnly ? `0 (\`${r.mobile.constants[0]}\` defined, unused)` : '—'} | ${r.mcp.join(', ') || '—'} |`),
].join('\n');

const note = read(NOTE);
const s = note.indexOf(START), e = note.indexOf(END);
if (s < 0 || e < 0) { console.error('api-map.md is missing its generated markers.'); process.exit(2); }
const next = `${note.slice(0, s + START.length)}\n${table}\n${note.slice(e)}`;
if (process.argv.includes('--check')) {
  if (next !== note) { console.error('api-map.md is STALE: run node tools/api-map.js'); process.exit(1); }
  console.log('api-map.md is current'); process.exit(0);
}
fs.writeFileSync(JSON_OUT, `${JSON.stringify(data, null, 1)}\n`);
fs.writeFileSync(NOTE, next);
console.log(`api-map: ${routes.length} routes → brain/context/api-map.md + brain/audits/data/api-map.json`);
